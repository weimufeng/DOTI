export function describeMbti(mbti: string): { code: string; name: string; blurb: string } {
  const hit = MBTI_COPY[mbti.toUpperCase()];
  return {
    code: mbti.toUpperCase(),
    name: hit?.name ?? "人格类型",
    blurb: hit?.blurb ?? "由答题中的内外向、感知、判断等倾向综合得出，仅供娱乐对照。",
  };
}

export function describeEnneagram(
  core: number,
  wing: number,
): { code: string; name: string; blurb: string } {
  const code = `${core}w${wing}`;
  const base = ENNE_CORE[core];
  const wingLine = ENNE_WING[code];
  return {
    code,
    name: base?.name ?? "九型",
    blurb: [base?.blurb, wingLine].filter(Boolean).join(""),
  };
}
